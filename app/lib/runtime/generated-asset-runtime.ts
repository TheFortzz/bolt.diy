import type { GeneratedAsset } from '~/lib/stores/generated-assets';

/**
 * Runtime bridge for generated images inside the preview iframe.
 *
 * `inlineGeneratedAssetUrls` rewrites *quoted* asset literals to data URLs at
 * build time, which covers the common `img.src = 'assets/car.png'` case. It
 * cannot cover a path the game builds at runtime (`'assets/' + name + '.png'`)
 * or a canvas/WebGL texture pipeline, so those games silently lost their art
 * and fell back to procedural shapes.
 *
 * This script is injected before the game code and:
 *
 * 1. Resolves any requested image path (literal, constructed, or an already
 *    inlined data URL) to the real generated bytes.
 * 2. Records whether each generated image was requested, loaded, and actually
 *    drawn (2D `drawImage`, a WebGL texture upload, or an ImageBitmap), so the
 *    verifier can prove the art is used instead of trusting a path mention.
 *
 * The recorded usage is exposed on `window.__STUDIO_ASSETS__` and read by the
 * preview probe. One copy lives in the static preview and (plain-JS twin) in
 * the exported `PREVIEW_ASSET_RUNTIME_MARKER`; keep them in sync.
 */
export const PREVIEW_ASSET_RUNTIME_MARKER = 'data-studio-asset-runtime';

export interface AssetRuntimeRecord {
  /** Canonical project-relative path, e.g. `assets/car.png`. */
  path: string;
  /** Basename (`car.png`) used to match loosely-constructed references. */
  base: string;
  dataUrl: string;
}

export function toAssetRuntimeRecords(
  assets: Record<string, Pick<GeneratedAsset, 'path' | 'dataUrl'>> | undefined,
): AssetRuntimeRecord[] {
  const records: AssetRuntimeRecord[] = [];

  for (const asset of Object.values(assets ?? {})) {
    if (!asset || typeof asset.path !== 'string' || typeof asset.dataUrl !== 'string') {
      continue;
    }

    if (!asset.dataUrl.startsWith('data:')) {
      continue;
    }

    const path = asset.path.replace(/\\/g, '/').replace(/^\.\//, '').replace(/^\/+/, '');

    if (!path) {
      continue;
    }

    records.push({
      path,
      base: path.split('/').pop() || path,
      dataUrl: asset.dataUrl,
    });
  }

  return records;
}

function escapeForInlineScript(value: string): string {
  return value.replace(/</g, '\\u003c').replace(/-->/g, '--\\u003e');
}

/**
 * The in-iframe runtime, as a plain-JS source string. Deliberately free of
 * backticks and `${` because it is embedded inside a TS template literal.
 */
export function generatedAssetRuntimeSource(records: AssetRuntimeRecord[]): string {
  const payload = escapeForInlineScript(JSON.stringify(records));

  return `(function(){
  if (window.__studioAssetRuntime) return;
  window.__studioAssetRuntime = true;
  var records = ${payload};
  if (!records.length) return;

  var state = { expected: [], requested: {}, loaded: {}, failed: {}, drawn: {} };
  var i;

  for (i = 0; i < records.length; i++) {
    state.expected.push(records[i].path);
  }

  function normalize(value) {
    var path = String(value == null ? '' : value).trim();
    try { path = decodeURIComponent(path); } catch (e) {}
    return path.replace(/[?#].*$/, '').replace(/\\\\/g, '/').replace(/^\\.\\//, '').replace(/^\\/+/, '');
  }

  function resolve(value) {
    if (value == null) return null;
    var raw = String(value);
    var j;

    if (raw.slice(0, 5) === 'data:') {
      for (j = 0; j < records.length; j++) {
        if (records[j].dataUrl === raw) return records[j];
      }
      return null;
    }

    var path = normalize(raw);
    var base = path.indexOf('/') === -1 ? path : path.split('/').pop();

    for (j = 0; j < records.length; j++) {
      if (records[j].path === path || records[j].base === base) return records[j];
    }

    return null;
  }

  function bump(bucket, path) {
    state[bucket][path] = (state[bucket][path] || 0) + 1;
  }

  window.__STUDIO_ASSETS__ = state;

  // 1. Image src assignment: resolve constructed paths and track load state.
  try {
    var descriptor = Object.getOwnPropertyDescriptor(HTMLImageElement.prototype, 'src');
    if (descriptor && descriptor.set) {
      Object.defineProperty(HTMLImageElement.prototype, 'src', {
        get: function() { return descriptor.get.call(this); },
        set: function(value) {
          var record = resolve(value);
          if (!record) { descriptor.set.call(this, value); return; }
          bump('requested', record.path);
          var element = this;
          try {
            if (!element.__studioAssetPath) {
              element.__studioAssetPath = record.path;
              element.addEventListener('load', function() { state.loaded[record.path] = true; });
              element.addEventListener('error', function() {
                state.failed[record.path] = String(element.getAttribute('src') || '').slice(0, 120);
              });
            }
          } catch (e) {}
          descriptor.set.call(this, record.dataUrl);
        },
        configurable: true,
        enumerable: true,
      });
    }
  } catch (e) {}

  // 2. Attribute-based references (createElement + setAttribute('src')).
  try {
    var nativeSetAttribute = Element.prototype.setAttribute;
    Element.prototype.setAttribute = function(name, value) {
      if (typeof value === 'string' && (name === 'src' || name === 'href' || name === 'poster')) {
        var record = resolve(value);
        if (record) { bump('requested', record.path); value = record.dataUrl; }
      }
      return nativeSetAttribute.call(this, name, value);
    };
  } catch (e) {}

  // 3. "Drawn" evidence: canvas 2D, WebGL texture upload, ImageBitmap.
  function markDrawn(image) {
    try {
      var src = image && (image.currentSrc || image.src);
      if (!src) return;
      var record = resolve(src);
      if (record) bump('drawn', record.path);
    } catch (e) {}
  }

  try {
    var proto2d = typeof CanvasRenderingContext2D !== 'undefined' ? CanvasRenderingContext2D.prototype : null;
    if (proto2d && proto2d.drawImage) {
      var nativeDrawImage = proto2d.drawImage;
      proto2d.drawImage = function(image) {
        markDrawn(image);
        return nativeDrawImage.apply(this, arguments);
      };
    }
  } catch (e) {}

  // ImageBitmap keeps no src back-reference, so createImageBitmap() counts as use.
  if (typeof window.createImageBitmap === 'function') {
    var nativeCreateImageBitmap = window.createImageBitmap;
    window.createImageBitmap = function(image) {
      markDrawn(image);
      return nativeCreateImageBitmap.apply(this, arguments);
    };
  }

  function instrumentTextureUploads(Context) {
    if (!Context || !Context.prototype) return;
    var methods = ['texImage2D', 'texSubImage2D'];
    for (var m = 0; m < methods.length; m++) {
      (function(method) {
        var native = Context.prototype[method];
        if (typeof native !== 'function') return;
        Context.prototype[method] = function() {
          for (var a = 0; a < arguments.length; a++) {
            var arg = arguments[a];
            if (arg && typeof arg === 'object' && (arg.currentSrc || arg.src)) { markDrawn(arg); }
          }
          return native.apply(this, arguments);
        };
      })(methods[m]);
    }
  }

  instrumentTextureUploads(typeof WebGLRenderingContext !== 'undefined' ? WebGLRenderingContext : null);
  instrumentTextureUploads(typeof WebGL2RenderingContext !== 'undefined' ? WebGL2RenderingContext : null);

  // 4. fetch/XHR so await fetch('assets/x.png') style loaders work too.
  if (typeof window.fetch === 'function') {
    var nativeFetch = window.fetch;
    window.fetch = function(input, init) {
      try {
        var record = resolve(typeof input === 'string' ? input : input && input.url);
        if (record) return nativeFetch.call(this, record.dataUrl, init);
      } catch (e) {}
      return nativeFetch.apply(this, arguments);
    };
  }

  try {
    var nativeOpen = XMLHttpRequest.prototype.open;
    XMLHttpRequest.prototype.open = function(method, url) {
      var record = resolve(url);
      if (record) { arguments[1] = record.dataUrl; }
      return nativeOpen.apply(this, arguments);
    };
  } catch (e) {}
})();`;
}

/**
 * Returns the `<script>` block for the given assets, or an empty string when
 * there is nothing to resolve (keeps the preview byte-identical when a game
 * uses no generated art).
 */
export function buildGeneratedAssetRuntimeScript(
  assets: Record<string, Pick<GeneratedAsset, 'path' | 'dataUrl'>> | undefined,
): string {
  const records = toAssetRuntimeRecords(assets);

  if (!records.length) {
    return '';
  }

  return `<script ${PREVIEW_ASSET_RUNTIME_MARKER}>${generatedAssetRuntimeSource(records)}</script>`;
}

export interface GeneratedAssetUsage {
  /** Canonical path -> times the game asked for it. */
  requested: Record<string, number>;
  /** Canonical path -> loaded successfully. */
  loaded: Record<string, boolean>;
  /** Canonical path -> load failure detail. */
  failed: Record<string, string>;
  /** Canonical path -> times the pixels were actually drawn/uploaded. */
  drawn: Record<string, number>;
  expected: string[];
}

/**
 * Read the runtime usage report from a preview window. Pure so the probe (which
 * is stringified into the iframe and cannot import helpers) mirrors the same
 * rule with its own inline copy.
 */
export function describeUnusedGeneratedAssets(usage: GeneratedAssetUsage | undefined | null): string | undefined {
  if (!usage || !Array.isArray(usage.expected) || usage.expected.length === 0) {
    return undefined;
  }

  const broken = usage.expected.find((path) => usage.failed?.[path]);

  if (broken) {
    return `Generated image failed to load: ${broken}`;
  }

  /*
   * Requested + loaded but never drawn means the game fetched the art and then
   * painted a procedural substitute anyway; that is the exact bug this check
   * exists to catch.
   */
  const undrawn = usage.expected.filter(
    (path) => (usage.requested?.[path] || 0) > 0 && (usage.loaded?.[path] || false) && !(usage.drawn?.[path] || 0),
  );

  if (undrawn.length > 0) {
    return `Generated images were loaded but never drawn: ${undrawn.join(', ')}`;
  }

  return undefined;
}
