import { describe, expect, it } from 'vitest';
import {
  buildGeneratedAssetRuntimeScript,
  describeUnusedGeneratedAssets,
  generatedAssetRuntimeSource,
  PREVIEW_ASSET_RUNTIME_MARKER,
  toAssetRuntimeRecords,
} from './generated-asset-runtime';

const png = (marker: string) => `data:image/png;base64,${marker}`;

describe('generated asset runtime bridge', () => {
  it('keeps only resolvable image assets and derives a basename for loose matches', () => {
    const records = toAssetRuntimeRecords({
      'assets/sprites/car.png': { path: 'assets/sprites/car.png', dataUrl: png('AAAA') },
      'assets/models/crate.glb': { path: 'assets/models/crate.glb', dataUrl: 'data:model/gltf-binary;base64,BBBB' },
      'assets/broken.png': { path: 'assets/broken.png', dataUrl: 'https://cdn.example.com/broken.png' },
    });

    expect(records).toHaveLength(2);
    expect(records[0]).toMatchObject({ path: 'assets/sprites/car.png', base: 'car.png' });
    expect(records[1]).toMatchObject({ path: 'assets/models/crate.glb', base: 'crate.glb' });
  });

  it('produces nothing when the game uses no generated images', () => {
    expect(buildGeneratedAssetRuntimeScript({})).toBe('');
    expect(buildGeneratedAssetRuntimeScript(undefined)).toBe('');
  });

  it('emits a head-ready script carrying the asset map and the draw-tracking hooks', () => {
    const script = buildGeneratedAssetRuntimeScript({
      'assets/car.png': { path: 'assets/car.png', dataUrl: png('ZZZZ') },
    });

    expect(script).toContain(PREVIEW_ASSET_RUNTIME_MARKER);
    expect(script).toContain('assets/car.png');
    expect(script).toContain('__STUDIO_ASSETS__');
    // The two behaviours that make images actually appear and be verified.
    expect(script).toContain('drawImage');
    expect(script).toContain('HTMLImageElement.prototype');
    expect(script).toContain('texImage2D');
  });

  it('escapes angle brackets from the asset map so a script cannot break out', () => {
    const source = generatedAssetRuntimeSource([
      { path: 'assets/evil</script>.png', base: 'evil</script>.png', dataUrl: png('AAAA') },
    ]);

    expect(source.includes('</script')).toBe(false);
  });

  it('flags a generated image that loaded but was never drawn', () => {
    expect(
      describeUnusedGeneratedAssets({
        expected: ['assets/car.png'],
        requested: { 'assets/car.png': 1 },
        loaded: { 'assets/car.png': true },
        failed: {},
        drawn: {},
      }),
    ).toContain('never drawn');

    expect(
      describeUnusedGeneratedAssets({
        expected: ['assets/car.png'],
        requested: { 'assets/car.png': 2 },
        loaded: { 'assets/car.png': true },
        failed: {},
        drawn: { 'assets/car.png': 42 },
      }),
    ).toBeUndefined();
  });

  it('flags a generated image that failed to load', () => {
    expect(
      describeUnusedGeneratedAssets({
        expected: ['assets/car.png'],
        requested: { 'assets/car.png': 1 },
        loaded: {},
        failed: { 'assets/car.png': 'net::ERR' },
        drawn: {},
      }),
    ).toContain('failed to load');
  });

  it('does not judge assets it was never told about', () => {
    expect(describeUnusedGeneratedAssets(undefined)).toBeUndefined();
    expect(
      describeUnusedGeneratedAssets({ expected: [], requested: {}, loaded: {}, failed: {}, drawn: {} }),
    ).toBeUndefined();
  });
});

/**
 * The resolver is injected as a plain string, so it is exercised with a stub
 * DOM. This is the part that makes a dynamically-built path actually find the
 * generated bytes, and it is worth proving rather than trusting.
 */
describe('generated asset runtime execution', () => {
  const buildStubs = () => {
    const imageProto: Record<string, unknown> = {};
    Object.defineProperty(imageProto, 'src', {
      configurable: true,
      get(this: { _src?: string }) {
        return this._src || '';
      },
      set(this: { _src?: string }, value: string) {
        this._src = value;
      },
    });

    const elementProto = { setAttribute() {} };
    const contextProto = { drawImage() {} };
    const windowStub: Record<string, unknown> = {};

    return { imageProto, elementProto, contextProto, windowStub };
  };

  const run = (source: string, stubs: ReturnType<typeof buildStubs>) => {
    const factory = new Function(
      'window',
      'HTMLImageElement',
      'Element',
      'XMLHttpRequest',
      'CanvasRenderingContext2D',
      'WebGLRenderingContext',
      'WebGL2RenderingContext',
      'ImageBitmap',
      source,
    );

    factory(
      stubs.windowStub,
      { prototype: stubs.imageProto },
      { prototype: stubs.elementProto },
      undefined,
      { prototype: stubs.contextProto },
      undefined,
      undefined,
      undefined,
    );
  };

  it('parses as valid JavaScript', () => {
    const source = generatedAssetRuntimeSource([{ path: 'assets/car.png', base: 'car.png', dataUrl: png('QUJD') }]);

    expect(() => new Function(source)).not.toThrow();
  });

  it('rewrites a dynamically-built image path to the generated data URL', () => {
    const stubs = buildStubs();
    run(generatedAssetRuntimeSource([{ path: 'assets/car.png', base: 'car.png', dataUrl: png('QUJD') }]), stubs);

    const image = Object.create(stubs.imageProto) as Record<string, unknown> & {
      addEventListener: () => void;
      getAttribute: () => string;
    };
    image.addEventListener = () => {};
    image.getAttribute = () => '';

    // Exactly the pattern inlineGeneratedAssetUrls cannot see.
    const folder = 'assets';
    const name = 'car';
    (image as unknown as { src: string }).src = `${folder}/${name}.png`;

    expect((image as { _src?: string })._src).toBe(png('QUJD'));

    const usage = stubs.windowStub.__STUDIO_ASSETS__ as {
      expected: string[];
      requested: Record<string, number>;
    };
    expect(usage.expected).toEqual(['assets/car.png']);
    expect(usage.requested['assets/car.png']).toBe(1);
  });

  it('matches by basename when the game only uses the file name', () => {
    const stubs = buildStubs();
    run(generatedAssetRuntimeSource([{ path: 'assets/car.png', base: 'car.png', dataUrl: png('QUJD') }]), stubs);

    const image = Object.assign(Object.create(stubs.imageProto), {
      addEventListener() {},
      getAttribute() {
        return '';
      },
    }) as { src: string; _src?: string; addEventListener: () => void; getAttribute: () => string };
    image.src = 'car.png';

    expect(image._src).toBe(png('QUJD'));
  });
});
